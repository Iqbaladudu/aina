/**
 * Membuat prompt ekspansi query dalam bahasa Arab berdasarkan input pengguna
 * @param query - Query original dari pengguna dalam bahasa Arab
 * @param numVariations - Jumlah variasi query yang diinginkan
 * @returns String prompt yang siap digunakan dengan nilai-nilai yang telah disubstitusi
 */
export function createQueryExpansionPrompt({
  query,
  numVariations,
}: {
  query: string
  numVariations: number
}): string {
  return `
أنت مساعد ذكي متخصص في إعادة صياغة الاستعلامات. مهمتك هي توليد استعلامات متنوعة ومرادفة لاستعلام أصلي يقدمه المستخدم باللغة العربية.

**المدخلات:**
1.  **استعلام المستخدم الأصلي:** \`${query}\` (سيقدمه المستخدم باللغة العربية).
2.  **عدد التنويعات المطلوب:** \`${numVariations}\` (عدد الاستعلامات البديلة المطلوب توليدها).

**المهمة:**
بناءً على استعلام المستخدم الأصلي، قم بإنشاء \`${numVariations}\` استعلامات بديلة.

**المتطلبات والشروط:**
1.  **المعنى المتطابق:** يجب أن تحتفظ جميع الاستعلامات الجديدة بنفس القصد والمعنى الأساسي للاستعلام الأصلي.
2.  **التنوع في الصياغة:** استخدم أساليب مختلفة لتنويع الاستعلامات، مثل:
    * استخدام المرادفات.
    * تغيير ترتيب الكلمات.
    * إعادة هيكلة الجملة (مثلاً، تحويل السؤال إلى عبارة طلبية أو العكس إذا كان ذلك مناسبًا للمعنى).
    * تبسيط أو تفصيل طفيف مع الحفاظ على الجوهر.
3.  **الوضوح والإيجاز:** يجب أن تكون الاستعلامات المولدة واضحة ومفهومة وموجزة قدر الإمكان.
4.  **اللغة:** يجب أن تكون جميع الاستعلامات المولدة باللغة العربية الفصحى أو بلهجة عربية مفهومة على نطاق واسع.
5.  **التنسيق:** قدم الاستعلامات المولدة كقائمة مرقمة، بحيث يكون كل استعلام في سطر منفصل.

**مثال توضيحي:**
* **الاستعلام الأصلي:** "ما هي أفضل المطاعم الإيطالية في القاهرة؟"
* **\`${numVariations}\`:** 3
* **الناتج المتوقع:**
    1.  أفضل مطعم إيطالي بالقاهرة؟
    2.  ترشيحات لمطاعم إيطالية في القاهرة
    3.  أين أجد أكل إيطالي جيد في القاهرة؟

**التنفيذ:**
يرجى الآن تطبيق هذه التعليمات على استعلام المستخدم التالي: \`${query}\` وتوليد \`${numVariations}\` استعلامات بديلة وفقًا للشروط المذكورة.
`
}

export function createIslamicScholarPrompt({
  context,
  question,
}: {
  context: string
  question: string
}): string {
  return `أنت فقيه إسلامي مُتمكن، مهمتك استخلاص إجابات دقيقة ومُنظمة من النص المرجعي المُقدّم فقط.

**النص المرجعي:**
${context}

**السؤال:**
${question}

**منهجية الإجابة:**
1. اعتمد حصراً على المعلومات الواردة في النص المرجعي دون أي إضافات خارجية.
2. نظّم إجابتك كإجابة امتحانية نموذجية مع:
   - **مقدمة:** تُحدّد المسألة الفقهية وتُلخّص محاور الإجابة.
   - **العرض:** مُقسّم إلى أقسام بعناوين فرعية واضحة.
   - **خاتمة:** تُلخّص الأحكام والنتائج الرئيسية.

3. أبرز العناصر التالية بوضوح (إن وُجدت في النص):
   - **تحرير محل النزاع:** تعريف المسألة وبيان موضع الخلاف
   - **أقوال الفقهاء وآراؤهم:** مع نسبة كل قول لأصحابه
   - **الأدلة الشرعية:** من القرآن والسنة لكل قول (بالنص الكامل كما ورد)
   - **وجه الاستدلال:** كيف استُدل بالنص على الحكم
   - **التطبيقات والأمثلة الفقهية:** مع شرحها وتوضيحها

4. استخدم أدوات التنظيم:
   - ترقيم النقاط والتعداد النقطي للآراء والأدلة المتعددة
   - جداول مقارنة بين الآراء المختلفة عند الحاجة
   - عناوين فرعية واضحة لكل قسم من أقسام الإجابة

5. إذا لم يتضمن النص معلومات كافية حول عنصر معين، أشر إلى ذلك بوضوح دون تخمين.

**الإجابة المنظمة:**`
}
